# Build-only benchmark: polynomial/registry construction is outside the timer;
# checked Problem/Relaxation construction is inside. No optimizer is attached or run.
include("../core/benchmark_build.jl")

model_program(H,order) = Nx.build(Nx.Problem(H),Nx.Relaxation(order=order))
model_standard(H,order) = Nx.moment_standard_form(model_program(H,order).program)
model_jump(H,order) = Nx.to_jump(model_standard(H,order))
legacy_program(H,registry,order) = old_pipeline(polyopt(H,registry),SolverConfig(optimizer=COSMO.Optimizer,order=order))
legacy_jump(H,registry,order) = build_jump_model(legacy_program(H,registry,order))

function compare_model(name,oldH,registry,H,order;site_word=false)
    old = legacy_program(oldH,registry,order)
    built = model_program(H,order)
    W = eltype(built.table.keys)
    convert_word(m) = Nx.word_from_legacy(W,site_word ? [(mod1(NCTSSoS.decode_operator_id(l),2)<<8)|NCTSSoS.decode_site(l) for l in m.word] : m.word)
    @test Set(Nx.moment_key(convert_word(m))[1] for m in values(old.linear.key_to_monomial))==Set(label.word for label in built.table.labels)
    println(name," rows=",built.sizes.rows," keys=",built.sizes.moments," word_bytes=",sizeof(W))
    measure_build("$name legacy checked rows+program",legacy_program,oldH,registry,order)
    measure_build("$name model checked rows+program",model_program,H,order)
    measure_build("$name model checked through standard",model_standard,H,order)
    measure_build("$name legacy checked through JuMP",legacy_jump,oldH,registry,order)
    measure_build("$name model checked through JuMP",model_jump,H,order)
end
function model_benchmarks()
    println("Julia=",VERSION," CPU=",Sys.CPU_NAME," threads=",Threads.nthreads()," samples=7 GC outside timer")
    reg,(x,y,z) = create_pauli_variables(1:10)
    oldH = sum(x[i]*x[i+1]+y[i]*y[i+1]+z[i]*z[i+1] for i in 1:9)
    _,(x,y,z) = Nx.pauli_variables(10)
    H = sum(x[i]*x[i+1]+y[i]*y[i+1]+z[i]*z[i+1] for i in 1:9)
    compare_model("Heisenberg10/d2",oldH,reg,H,2)
    reg,(a,ad) = create_fermionic_variables(1:4)
    oldH = -(ad[1]*a[3]+ad[3]*a[1]+ad[2]*a[4]+ad[4]*a[2])+2*(ad[1]*a[1]*ad[2]*a[2]+ad[3]*a[3]*ad[4]*a[4])
    _,(a,ad) = Nx.fermionic_variables(4)
    H = -(ad[1]*a[3]+ad[3]*a[1]+ad[2]*a[4]+ad[4]*a[2])+2*(ad[1]*a[1]*ad[2]*a[2]+ad[3]*a[3]*ad[4]*a[4])
    compare_model("Hubbard2/d2",oldH,reg,H,2)
    reg,(x,y) = create_unipotent_variables([("x",1:2),("y",1:2)])
    oldH = -(x[1]*y[1]+x[1]*y[2]+x[2]*y[1]-x[2]*y[2])
    _,(x,y) = Nx.site_variables(Nx.Unipotent(),2,2)
    H = -(x[1]*y[1]+x[1]*y[2]+x[2]*y[1]-x[2]*y[2])
    compare_model("CHSH/d2",oldH,reg,H,2;site_word=true)
end
model_benchmarks()
